#!/usr/bin/env python3
"""Writes the Rust tables of the realistic device frames from the manifest.

    python3 native/scripts/device-art-table.py

The drawings and `manifest.json` under
`crates/specular-app/assets/device-frames/` come from
`scripts/device-frames/convert.py`. This script picks the drawings the
viewport presets use and writes two files, which are checked in:

- `crates/specular-doc/src/device_art/table.rs`: `DeviceArt`, each
  drawing's geometry, and which preset device is drawn as which.
- `crates/specular-app/src/images/device_frames/drawings.rs`: the SVG
  files in the binary.

Run it after the manifest changes or a preset's drawing does. A drawing the
manifest does not have yet is left out, and its devices are drawn in clay.
A test in `specular-app` fails when the tables and the manifest disagree.
"""

import json
import subprocess
import sys
from pathlib import Path

NATIVE = Path(__file__).resolve().parent.parent
ASSETS = NATIVE / "crates/specular-app/assets/device-frames"
DOC_TABLE = NATIVE / "crates/specular-doc/src/device_art/table.rs"
APP_TABLE = NATIVE / "crates/specular-app/src/images/device_frames/drawings.rs"

# A preset's `deviceId` and the drawing it is shown in: the manifest's
# `name`. The id says which preset and the name which drawing, so a newer
# phone with the same screen and front can use an older body.
DEVICE_ART = {
    "iphone-17-pro-max": "iphone-16-pro-max",
    "iphone-17": "iphone-16-pro",
    "iphone-air": "iphone-air",
    "iphone-14-pro-max": "iphone-16-plus",
    "iphone-14-pro": "iphone-16",
    "iphone-16e": "iphone-13",
    "iphone-se": "iphone-se",
    "pixel-10-pro-xl": "google-pixel-9-pro-xl",
    "pixel-10": "google-pixel-9",
    "galaxy-s25": "samsung-galaxy-s25",
    "ipad-pro-13": "ipad-pro-13-inches-m4",
    "ipad-pro-11-m4": "ipad-pro-11-inches-m4",
    "ipad-pro-129": "ipad-pro-12inches-gen4",
    "ipad-air-11": "ipad-air-4",
    "ipad-mini": "ipad-mini",
    "ipad-pro-11": "ipad-pro-11inches",
}

HEADER = "// @generated by native/scripts/device-art-table.py from the device frames'\n// manifest.json. Do not edit by hand.\n\n"


def variant(name):
    return "".join(part.capitalize() for part in name.split("-"))


def number(value):
    return repr(float(value))


def doc_table(rows):
    out = [HEADER, "use super::{ArtGeometry, DeviceFrameColor};\n\n"]
    out.append("/// A drawing of a device: one of the realistic frames.\n")
    out.append("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]\npub enum DeviceArt {\n")
    for row in rows:
        out.append(f"    /// `{row['name']}`.\n    {variant(row['name'])},\n")
    out.append("}\n\nimpl DeviceArt {\n")
    out.append(f"    /// Every drawing.\n    pub const ALL: [Self; {len(rows)}] = [\n")
    out.extend(f"        Self::{variant(row['name'])},\n" for row in rows)
    out.append("    ];\n\n")

    out.append("    /// The drawing a page of the preset device `device_id` is shown in.\n")
    out.append("    pub fn of_device(device_id: &str) -> Option<Self> {\n        match device_id {\n")
    names = {row["name"] for row in rows}
    for device, art in DEVICE_ART.items():
        if art in names:
            out.append(f'            "{device}" => Some(Self::{variant(art)}),\n')
    out.append("            _ => None,\n        }\n    }\n\n")

    out.append("    /// The drawing's `name` in the manifest, which is its file's stem.\n")
    out.append("    pub const fn name(self) -> &'static str {\n        match self {\n")
    out.extend(f'            Self::{variant(row["name"])} => "{row["name"]}",\n' for row in rows)
    out.append("        }\n    }\n\n")

    out.append("    /// Whether the device is a tablet and not a phone.\n")
    tablets = " | ".join(f"Self::{variant(row['name'])}" for row in rows if row["kind"] == "tablet")
    out.append(f"    pub const fn is_tablet(self) -> bool {{\n        matches!(self, {tablets})\n    }}\n\n")

    out.append("    /// The name the drawing in `color` is asked for by, where a file\n")
    out.append("    /// entity's image is asked for by its path. It is no path: the shell\n")
    out.append("    /// holds the drawings. A device with no light drawing is dark in both.\n")
    out.append("    pub const fn asset(self, color: DeviceFrameColor) -> &'static str {\n        match (self, color) {\n")
    for row in rows:
        dark = f"specular-device-frame:{row['file']}"
        light = f"specular-device-frame:{row.get('lightFile', row['file'])}"
        out.append(f'            (Self::{variant(row["name"])}, DeviceFrameColor::Dark) => "{dark}",\n')
        out.append(f'            (Self::{variant(row["name"])}, DeviceFrameColor::Light) => "{light}",\n')
    out.append("        }\n    }\n\n")

    out.append("    /// Where the screen and the body sit in the drawing: the manifest's\n")
    out.append("    /// `frame`, `screen`, `screenCornerRadius`, `body` and\n    /// `bodyCornerRadius`.\n")
    out.append('    #[expect(clippy::too_many_lines, reason = "a generated table, a row a drawing")]\n')
    out.append("    pub const fn geometry(self) -> ArtGeometry {\n        match self {\n")
    for row in rows:
        frame, screen, body = row["frame"], row["screen"], row["body"]
        out.append(
            f"            Self::{variant(row['name'])} => ArtGeometry {{\n"
            f"                frame: ({number(frame['width'])}, {number(frame['height'])}),\n"
            f"                screen_origin: ({number(screen['x'])}, {number(screen['y'])}),\n"
            f"                screen_size: ({number(screen['width'])}, {number(screen['height'])}),\n"
            f"                screen_corner_radius: {number(row['screenCornerRadius'])},\n"
            f"                body_origin: ({number(body['x'])}, {number(body['y'])}),\n"
            f"                body_size: ({number(body['width'])}, {number(body['height'])}),\n"
            f"                body_corner_radius: {number(row['bodyCornerRadius'])},\n"
            f"            }},\n"
        )
    out.append("        }\n    }\n}\n")
    return "".join(out)


def app_table(rows):
    out = [HEADER, "use specular_doc::{DeviceArt, DeviceFrameColor};\n\n"]
    out.append("/// The SVG of `art` in `color`. A device with no light drawing is dark in\n/// both.\n")
    out.append("pub(super) const fn svg(art: DeviceArt, color: DeviceFrameColor) -> &'static [u8] {\n")
    out.append("    match (art, color) {\n")
    for row in rows:
        for color, file in (("Dark", row["file"]), ("Light", row.get("lightFile", row["file"]))):
            out.append(
                f"        (DeviceArt::{variant(row['name'])}, DeviceFrameColor::{color}) => {{\n"
                f'            include_bytes!("../../../assets/device-frames/{file}")\n        }}\n'
            )
    out.append("    }\n}\n")
    return "".join(out)


def main():
    manifest = {row["name"]: row for row in json.loads((ASSETS / "manifest.json").read_text())}
    wanted = sorted(set(DEVICE_ART.values()))
    rows = []
    for name in wanted:
        row = manifest.get(name)
        if row is None or "body" not in row:
            print(f"left out {name}: the manifest has no such drawing with a body", file=sys.stderr)
            continue
        rows.append(row)
    for path, text in ((DOC_TABLE, doc_table(rows)), (APP_TABLE, app_table(rows))):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        subprocess.run(["rustfmt", "--edition", "2024", str(path)], check=True)
    print(f"{len(rows)} drawings written")


if __name__ == "__main__":
    sys.exit(main())
